"""Generate committed responsive assets: python -m pip install Pillow==12.3.0

Run from any directory with: python scripts/optimize-images.py
Originals are retained. The founder photo is deliberately excluded.
No Python dependency is needed to build or serve the website.
"""
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
IMAGES = ROOT / "public/images"
OUTPUT = IMAGES / "optimized"
OUTPUT.mkdir(exist_ok=True)
sources = [
    "serpo-rank-official-logo.png",
    "services-hero.png",
    "on-page-seo-hero.png",
    "off-page-seo-hero.png",
    "local-seo-hero.webp",
    "technical-seo-hero.webp",
    "pricing-seo-blog-bonus.webp",
    *sorted(p.name for p in IMAGES.glob("certificate-*.jpeg")),
]
manifest = {}
for name in sources:
    source = IMAGES / name
    with Image.open(source) as image:
        width, height = image.size
        logo = "logo" in name
        certificate = name.startswith("certificate-")
        widths = [480, 960, 1440] if logo else sorted({480, 768, min(1200, width), width})
        variants = []
        for target_width in widths:
            target_height = round(height * target_width / width)
            resized = image.resize((target_width, target_height), Image.Resampling.LANCZOS)
            target = OUTPUT / f"{source.stem}-{target_width}.webp"
            resized.save(target, "WEBP", quality=92 if logo or certificate else 86, method=6)
            # Already efficient WebP originals need no additional lossy generation at full size.
            if source.suffix == ".webp" and target_width == width:
                target.unlink()
                target = source
            variants.append((target_width, "/" + target.relative_to(ROOT / "public").as_posix()))
        manifest[f"/images/{name}"] = {
            "src": variants[-1][1],
            "srcSet": ", ".join(f"{url} {w}w" for w, url in variants),
            "width": width,
            "height": height,
        }
        largest = ROOT / "public" / variants[-1][1].lstrip("/")
        print(f"{name}: {source.stat().st_size:,} -> {largest.stat().st_size:,} bytes (largest variant)")

destination = ROOT / "src/data/optimized-images.ts"
destination.write_text(
    '// Generated by scripts/optimize-images.py. Do not edit by hand.\n'
    'export const optimizedImages: Record<string, { src: string; srcSet: string; width: number; height: number }> = '
    + json.dumps(manifest, indent=2) + ';\n'
)
